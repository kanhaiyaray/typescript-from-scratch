// TypeScript Variables

// 1. let
let variableUserName: string = "Aman";
let variableAge: number = 25;

console.log(variableUserName);
console.log(variableAge);

// let can be changed
variableUserName = "Rahul";
variableAge = 30;

console.log(variableUserName);
console.log(variableAge);

// 2. const

const variableCountry: string = "India";
const variablePi: number = 3.14;

console.log(variableCountry);
console.log(variablePi);

// const cannot be reassigned

// 3. Different Data Types

let variableFirstName: string = "Aman";

let variableUserAge: number = 25;

let variableIsStudent: boolean = true;

console.log(variableFirstName);
console.log(variableUserAge);
console.log(variableIsStudent);


// 4. Multiple Variables

let variableCity: string = "Delhi";

let variableSalary: number = 50000;

let variableEmployed: boolean = true;

console.log(variableCity);
console.log(variableSalary);
console.log(variableEmployed);


// 5. Variable Naming

let variableProductName: string = "Laptop";

let variableProductPrice: number = 75000;

console.log(variableProductName);
console.log(variableProductPrice);


export {};